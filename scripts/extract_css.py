"""Copy Clayworks styles into the Storybook package so the app stays the single source.

Writes ui/styles/clayworks.css from:
  - the <style> block in app/clayworks.html (tokens, skin, components)
  - the account/login/dialog CSS that web/build.py adds for the GitHub build
and ui/.storybook/preview-head.html with the app's Google Fonts link.
Run automatically by `npm run storybook` / `npm run build-storybook` in ui/.
"""
import os, re

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
app = open(os.path.join(R, "app", "clayworks.html"), encoding="utf-8").read()
m = re.search(r"<style>(.*?)</style>", app, re.S)
assert m, "no <style> block in app/clayworks.html"
css = m.group(1)

build = open(os.path.join(R, "web", "build.py"), encoding="utf-8").read()
b = re.search(r"css = '''(.*?)</style>'''", build, re.S)
shim_css = b.group(1) if b else ""

fonts = re.search(r'<link rel="stylesheet" href="(https://fonts\.googleapis\.com/[^"]+)">', app)

out = os.path.join(R, "ui", "styles")
os.makedirs(out, exist_ok=True)
open(os.path.join(out, "clayworks.css"), "w", encoding="utf-8").write(
    "/* GENERATED by scripts/extract_css.py from app/clayworks.html and web/build.py. Edit those, not this. */\n"
    + css + "\n/* --- GitHub build: account menu, login, dialogs (web/build.py) --- */\n" + shim_css + "\n")
head = os.path.join(R, "ui", ".storybook")
os.makedirs(head, exist_ok=True)
open(os.path.join(head, "preview-head.html"), "w", encoding="utf-8").write(
    "<!-- GENERATED by scripts/extract_css.py -->\n"
    + (f'<link rel="stylesheet" href="{fonts.group(1)}">\n' if fonts else "")
    + "<style>[hidden]{display:none!important}</style>\n")
print(f"wrote ui/styles/clayworks.css ({len(css) + len(shim_css):,} chars) and ui/.storybook/preview-head.html")
